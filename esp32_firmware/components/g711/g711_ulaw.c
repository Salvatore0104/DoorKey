int16_t ulaw_to_pcm16(uint8_t ulaw)
{
    return ulaw_decode_table[ulaw];
}

void ulaw_to_pcm16_buf(const uint8_t *ulaw, int16_t *pcm, size_t samples)
{
    for (size_t i = 0; i < samples; i++) {
        pcm[i] = ulaw_decode_table[ulaw[i]];
    }
}

/* μ-law 编码 (PCM s16 → μ-law) */
uint8_t pcm16_to_ulaw(int16_t sample)
{
    const int16_t MULAW_MAX = 0x7F00;
    const uint16_t MULAW_BIAS = 0x84;
    int16_t sign = (sample >> 8) & 0x80;
    int16_t magnitude;

    if (sample < 0) {
        magnitude = -sample;
    } else {
        magnitude = sample;
    }
    if (magnitude > MULAW_MAX) {
        magnitude = MULAW_MAX;
    }
    magnitude += MULAW_BIAS;

    int16_t exponent = 7;
    int16_t mask = 0x4000;
    while ((magnitude & mask) == 0 && exponent > 0) {
        exponent--;
        mask >>= 1;
    }

    int16_t mantissa = (magnitude >> (exponent + 3)) & 0x0F;
    uint8_t ulaw_byte = ~(sign | (exponent << 4) | mantissa);
    return ulaw_byte;
}

void pcm16_to_ulaw_buf(const int16_t *pcm, uint8_t *ulaw, size_t samples)
{
    for (size_t i = 0; i < samples; i++) {
        ulaw[i] = pcm16_to_ulaw(pcm[i]);
    }
}
